// Command apigen generates the Go operation table and server interface from api/openapi.yaml (HP-API-001,
// ADR-0031). The spec is the source: every operation's method, path, permission and security flags come from it, and
// the server cannot compile without a handler for each operation.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"slices"
	"sort"
	"strings"

	"go.yaml.in/yaml/v3"
)

type operation struct {
	OperationID string   `yaml:"operationId"`
	Tags        []string `yaml:"tags"`
	Permission  string   `yaml:"x-permission"`
	Reauth      bool     `yaml:"x-reauth"`
	MFA         bool     `yaml:"x-mfa"`
	Idempotent  bool     `yaml:"x-idempotency-key"`
	Stream      bool     `yaml:"x-stream"`
	Redirect    bool     `yaml:"x-redirect"`
	Token       bool     `yaml:"x-token"`
}

type spec struct {
	OpenAPI string                          `yaml:"openapi"`
	Servers []struct{ URL string }          `yaml:"servers"`
	Paths   map[string]map[string]yaml.Node `yaml:"paths"`
}

var (
	methods = []string{"get", "post", "put", "patch", "delete"}
	opIDRE  = regexp.MustCompile(`^[a-z][A-Za-z0-9]*$`)
)

type row struct {
	operation
	Method, Path string
}

func main() {
	in := flag.String("spec", "api/openapi.yaml", "OpenAPI document")
	out := flag.String("out", "internal/httpapi/gen/operations.gen.go", "output file")
	flag.Parse()
	if err := run(*in, *out); err != nil {
		fmt.Fprintln(os.Stderr, "apigen:", err)
		os.Exit(1)
	}
}

func run(in, out string) error {
	raw, err := os.ReadFile(in) //nolint:gosec // G304: developer tool reading the spec path it was given
	if err != nil {
		return err
	}
	var s spec
	if err := yaml.Unmarshal(raw, &s); err != nil {
		return err
	}
	if !strings.HasPrefix(s.OpenAPI, "3.1") {
		return fmt.Errorf("openapi version %q: want 3.1.x", s.OpenAPI)
	}
	var rows []row
	seen := map[string]bool{}
	for path, item := range s.Paths {
		for _, m := range methods {
			node, ok := item[m]
			if !ok {
				continue
			}
			var op operation
			if err := node.Decode(&op); err != nil {
				return fmt.Errorf("%s %s: %w", m, path, err)
			}
			switch {
			case !opIDRE.MatchString(op.OperationID):
				return fmt.Errorf("%s %s: invalid or missing operationId %q", m, path, op.OperationID)
			case seen[op.OperationID]:
				return fmt.Errorf("duplicate operationId %s", op.OperationID)
			case op.Permission == "":
				return fmt.Errorf("%s: missing x-permission", op.OperationID)
			}
			seen[op.OperationID] = true
			rows = append(rows, row{operation: op, Method: strings.ToUpper(m), Path: path})
		}
	}
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].Path != rows[j].Path {
			return rows[i].Path < rows[j].Path
		}
		return slices.Index(methods, strings.ToLower(rows[i].Method)) < slices.Index(methods, strings.ToLower(rows[j].Method))
	})
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/tools/apigen from api/openapi.yaml. DO NOT EDIT.\n\npackage gen\n\n")
	b.WriteString("// Operations lists every API operation in the spec.\nvar Operations = []Operation{\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\t{ID: %q, Method: %q, Path: %q, Permission: %q, Reauth: %t, MFA: %t, Idempotent: %t, Stream: %t, Redirect: %t, Token: %t, Tags: %#v},\n",
			r.OperationID, r.Method, r.Path, r.Permission, r.Reauth, r.MFA, r.Idempotent, r.Stream, r.Redirect, r.Token, r.Tags)
	}
	b.WriteString("}\n\n// Server has one method per operation.\ntype Server interface {\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\t// %s %s %s (permission %s)\n\t%s(c *Call) (*Result, error)\n", exported(r.OperationID), r.Method, r.Path, r.Permission, exported(r.OperationID))
	}
	b.WriteString("}\n\n// Handlers maps operation IDs to the server's methods.\nfunc Handlers(s Server) map[string]Handler {\n\treturn map[string]Handler{\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\t\t%q: s.%s,\n", r.OperationID, exported(r.OperationID))
	}
	b.WriteString("\t}\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644) //nolint:gosec // generated source file
}

func exported(id string) string { return strings.ToUpper(id[:1]) + id[1:] }
